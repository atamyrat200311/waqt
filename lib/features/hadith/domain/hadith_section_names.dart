// Russian. The bundled data only has English names. Owner should review.

import 'hadith.dart';

/// Chapter name in the app language (English when no translation exists).
String hadithSectionName(String bookId, HadithSection s, String language) {
  final i = switch (language) {
    'tk' => 0,
    'tr' => 1,
    'ru' => 2,
    _ => -1,
  };
  if (i < 0) return s.name;
  final names = switch (bookId) {
    'bukhari' => s.id >= 1 && s.id <= _bukhari.length ? _bukhari[s.id - 1] : null,
    'muslim' => s.id >= 0 && s.id < _muslim.length ? _muslim[s.id] : null,
    'nawawi' => const ['Nawawynyň kyrk hadysy', 'Nevevî’nin Kırk Hadisi', 'Сорок хадисов ан-Навави'],
    'qudsi' => const ['Kyrk kudsy hadys', 'Kırk Kudsî Hadis', 'Сорок хадисов кудси'],
    _ => null,
  };
  return names?[i] ?? s.name;
}

