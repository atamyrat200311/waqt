// Converts the official Turkmenistan prayer-time table (tm_wagt_default.json)
// into lib/features/prayer/domain/tm_times_data.dart.
//
//   dart run tool/build_tm_times.dart path/to/tm_wagt_default.json
//
// Input: a JSON array — [header, index list, 12810 records, string pool].
// Each record {id, city 1–5, period 1–7, date, time}; date/time are indexes
// into the string pool ("01/07/2022", "2022-07-01T04:37:00.100Z"). Times are
// Turkmenistan wall-clock (UTC+5) despite the Z. Records are ordered city →
// day (Jan 1 … Feb 28, Feb 29 (2024), Mar 1 … Dec 31) → period.
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.isEmpty) {
    stderr.writeln('usage: dart run tool/build_tm_times.dart tm_wagt_default.json');
    exit(64);
  }
  var text = File(args.first).readAsStringSync();
  if (text.startsWith('﻿')) text = text.substring(1);
  final a = jsonDecode(text) as List<Object?>;
  final records = a.sublist(2, 12812).cast<Map<String, Object?>>();
  const cities = 5, days = 366, periods = 7;
  if (records.length != cities * days * periods) throw StateError('unexpected record count ${records.length}');

  final minutes = <int>[];
  for (var i = 0; i < records.length; i++) {
    final r = records[i];
    final city = i ~/ (days * periods) + 1;
    final day = (i % (days * periods)) ~/ periods;
    final period = i % periods + 1;
    if (r['city'] != city || r['period'] != period) throw StateError('record $i out of order');
    final date = a[int.parse(r['date']! as String)]! as String; // dd/MM/yyyy
    final dm = date.substring(0, 5);
    final expected = _dayMonth(day);
    if (dm != expected) throw StateError('record $i: date $date, expected $expected');
    final time = a[int.parse(r['time']! as String)]! as String; // yyyy-MM-ddTHH:mm…
    final h = int.parse(time.substring(11, 13));
    final m = int.parse(time.substring(14, 16));
    minutes.add(h * 60 + m);
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/build_tm_times.dart from the official Turkmenistan')
    ..writeln('// prayer-time table (tm_wagt_default.json). Do not edit by hand.')
    ..writeln('//')
    ..writeln('// Minutes after local midnight (UTC+5). Layout: [city][day][period], cities')
    ..writeln('// Ashgabat, Balkanabat, Daşoguz, Türkmenabat, Mary; days Jan 1 … Dec 31 of a')
    ..writeln('// leap year (index 59 = Feb 29); periods imsak, fajr, sunrise, dhuhr, asr,')
    ..writeln('// maghrib, isha.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('const tmTimesData = <int>[');
  for (var c = 0; c < cities; c++) {
    out.writeln('  // city ${c + 1}');
    for (var d = 0; d < days; d++) {
      final o = (c * days + d) * periods;
      out.writeln('  ${minutes.sublist(o, o + periods).join(', ')},');
    }
  }
  out.writeln('];');
  File('lib/features/prayer/domain/tm_times_data.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote ${minutes.length} times');
}

/// "dd/MM" of day index [i] in a leap year.
String _dayMonth(int i) {
  final d = DateTime(2024, 1, 1 + i);
  String two(int n) => n.toString().padLeft(2, '0');
  return '${two(d.day)}/${two(d.month)}';
}
